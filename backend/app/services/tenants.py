"""Tenant registration: PMP FR-01, "an organization can create a tenant account".

One transaction, three rows
---------------------------
A registration writes a tenant, its first administrator, and that
administrator's refresh token — in a single transaction owned by the caller.
That is not incidental. A half-registered organisation is a genuinely bad state
to be able to produce: a tenant with no user cannot be administered, no login
can succeed, and nothing in the API can repair it because every
user-management route requires an authenticated administrator who does not
exist. The alternative — committing the tenant and then discovering the user
insert failed — makes that state reachable.

This module therefore never commits. It adds rows and flushes (so constraint
violations surface here, with the session still usable for a rollback) and
returns. :func:`app.db.session.get_db` commits on the way out of the request
handler and rolls back on any exception, which is the transaction boundary the
whole application already uses.

Why the first user is always an administrator
--------------------------------------------
PMP FR-03 makes role assignment an administrator's job. If a tenant could be
registered with a non-administrator first user, that tenant would have nobody
able to promote anyone, and no route could ever fix it: every user-management
endpoint requires an authenticated administrator. So the role is not a request
field — it is not an input at all — and this is the only place in the codebase
that assigns :attr:`~app.models.user.UserRole.ADMIN` outside of an existing
administrator's decision.

Why no tenant id is accepted
----------------------------
The tenant's primary key is generated by the model
(:func:`uuid.uuid4`) and is not an input. Accepting one would let a client
choose its own identifier, and a guessed or leaked UUID would then be a
collision waiting to happen. There is nothing in PMP §14 or §15 that requires
a caller-chosen tenant id, so there is no reason to accept one.
"""

from __future__ import annotations

from dataclasses import dataclass

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.core.config import Settings
from app.core.config import settings as process_settings
from app.core.security import hash_password
from app.models.tenant import Tenant
from app.models.user import User, UserRole
from app.services.auth import IssuedTokens, issue_token_pair


class TenantSlugUnavailableError(ValueError):
    """The requested slug is already registered.

    Raised both for the pre-check (a slug already present) and for a constraint
    violation caught at flush time. The second case is the one that matters for
    correctness: two concurrent registrations of the same slug both pass the
    pre-check, and only the database can adjudicate. The pre-check exists to
    produce a good error message in the common case, not to enforce the rule.
    """


@dataclass(frozen=True, slots=True)
class RegistrationResult:
    """What a successful registration produced.

    ``tokens`` is the new administrator's first session. It is issued here
    rather than requiring a follow-up ``/auth/login`` because the caller has
    just supplied the tenant's only credential; see
    :class:`app.schemas.auth.TenantRegistrationResponse` for why this widens
    nothing an attacker could not obtain by logging in anyway.
    """

    tenant: Tenant
    admin: User
    tokens: IssuedTokens


def _resolve(app_settings: Settings | None) -> Settings:
    """Return the settings to use, defaulting to the process-wide instance.

    Mirrors :func:`app.services.auth._resolve`, so every function in
    :mod:`app.services` has the same optional-settings convention.
    """
    return process_settings if app_settings is None else app_settings


def register_tenant(
    session: Session,
    *,
    name: str,
    slug: str,
    admin_email: str,
    admin_password: str,
    app_settings: Settings | None = None,
) -> RegistrationResult:
    """Create a tenant and its first administrator, and sign the administrator in.

    Args:
        session: an open database session. The caller owns the transaction; this
            function never commits.
        name: the tenant's display name. Validated by the request schema.
        slug: the tenant's URL slug, already folded to lower case by the request
            schema. Unique across all tenants.
        admin_email: the first administrator's login address, already folded to
            lower case by the request schema.
        admin_password: their password, in plaintext, hashed here with Argon2.
        app_settings: settings override, for tests.

    Returns:
        A :class:`RegistrationResult` holding the tenant, the administrator and
        a freshly issued token pair. The token's ``tenant_id`` claim is
        ``tenant.id``, so the caller is immediately inside their own tenant and
        nothing about the tenant boundary is left to be inferred.

    Raises:
        TenantSlugUnavailableError: the slug is already registered.
    """
    config = _resolve(app_settings)

    existing = session.scalar(select(Tenant.id).where(Tenant.slug == slug))
    if existing is not None:
        raise TenantSlugUnavailableError("that tenant slug is already registered")

    tenant = Tenant(name=name, slug=slug)
    session.add(tenant)

    try:
        # Flushed before the user is built, so a slug collision raises here with
        # nothing else written and the session can still be rolled back cleanly.
        session.flush()
    except IntegrityError as exc:
        session.rollback()
        raise TenantSlugUnavailableError(
            "that tenant slug is already registered"
        ) from exc

    admin = User(
        tenant_id=tenant.id,
        email=admin_email,
        password_hash=hash_password(admin_password),
        role=UserRole.ADMIN,
        is_active=True,
    )
    session.add(admin)
    session.flush()

    tokens = issue_token_pair(
        user=admin,
        tenant=tenant,
        session=session,
        app_settings=config,
    )

    return RegistrationResult(tenant=tenant, admin=admin, tokens=tokens)
